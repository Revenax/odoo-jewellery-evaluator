"""Build jewellery_website/static/src/css/icons.css from Lucide SVGs.

    npm pack lucide-static@0.460.0 && tar -xzf lucide-static-0.460.0.tgz
    python3 scripts/website/build_icons.py package/icons

Each Font Awesome / Odoo UI class in MAP is redrawn as a CSS mask of the Lucide icon
(stroke 1.5) in currentColor, scoped to the website (#wrapwrap). Add a class to MAP
when a new icon shows up on the shop.
"""
import re
import sys
import urllib.parse
from pathlib import Path

MAP = {
    'shopping-bag': ['fa-shopping-cart', 'fa-cart-plus'], 'heart': ['fa-heart-o'], 'heart@fill': ['fa-heart'],
    'arrow-right': ['oi-arrow-right'], 'x': ['oi-close', 'fa-times', 'fa-close', 'fa-remove'],
    'chevron-left': ['oi-chevron-left', 'fa-angle-left', 'fa-chevron-left'],
    'chevron-right': ['oi-chevron-right', 'fa-angle-right', 'fa-chevron-right'],
    'chevron-up': ['oi-chevron-up', 'fa-angle-up', 'fa-chevron-up'],
    'chevron-down': ['oi-chevron-down', 'fa-angle-down', 'fa-chevron-down', 'fa-caret-down'],
    'chevrons-left': ['fa-angle-double-left'], 'chevrons-right': ['fa-angle-double-right'],
    'phone': ['fa-phone'], 'mail': ['fa-envelope', 'fa-envelope-o'], 'plus': ['oi-plus', 'fa-plus'],
    'minus': ['oi-minus', 'fa-minus'], 'calendar': ['fa-calendar'], 'search': ['oi-search', 'fa-search'],
    'triangle-alert': ['fa-warning', 'fa-exclamation-triangle'], 'pencil': ['fa-pencil', 'fa-edit', 'fa-pencil-square-o'],
    'truck': ['fa-truck'], 'info': ['fa-info-circle', 'fa-info'], 'trash-2': ['fa-trash', 'fa-trash-o'],
    'download': ['fa-download'], 'zap': ['fa-bolt'], 'list': ['oi-view-list', 'fa-list'],
    'layout-grid': ['oi-apps', 'fa-th', 'fa-th-large'], 'sliders-horizontal': ['oi-settings-adjust', 'fa-sliders'],
    'map-pin': ['fa-map-marker'], 'lock': ['fa-lock'], 'globe': ['fa-globe'], 'arrow-left-right': ['fa-exchange'],
    'shopping-basket': ['fa-shopping-basket'], 'share-2': ['fa-share-alt'], 'tags': ['fa-tags', 'fa-tag'],
    'arrow-up-down': ['fa-sort'], 'rotate-ccw': ['fa-rotate-left', 'fa-undo'],
    'rotate-cw': ['fa-rotate-right', 'fa-refresh', 'fa-repeat'], 'printer': ['fa-print'],
    'move-right': ['fa-long-arrow-right', 'fa-arrow-right'], 'move-left': ['fa-long-arrow-left', 'fa-arrow-left'],
    'move-down': ['fa-long-arrow-down'], 'image': ['fa-image', 'fa-picture-o'], 'house': ['fa-home'],
    'file': ['fa-file', 'fa-file-o'], 'eye': ['fa-eye'], 'message-circle': ['fa-comment', 'fa-comment-o'],
    'send': ['fa-paper-plane'], 'check': ['fa-check', 'oi-check'], 'circle-check': ['fa-check-circle'],
    'user': ['fa-user', 'fa-user-o'], 'log-out': ['fa-sign-out'], 'credit-card': ['fa-credit-card'],
    'store': ['fa-shopping-bag'], 'circle-alert': ['fa-exclamation-circle'],
}
OUT = Path(__file__).resolve().parents[2] / 'jewellery_website/static/src/css/icons.css'


def main(icons_dir):
    css = ['/* Copyright 2026 Revenax Digital Services',
           ' * One thin-line icon set for the website: Lucide (ISC licence, lucide.dev), stroke 1.5.',
           ' * Font Awesome / Odoo UI icon classes keep working: each glyph is replaced by a CSS',
           ' * mask of the Lucide SVG, drawn in currentColor. Brand logos and fa-circle status',
           ' * dots are left alone. Generated by scripts/website/build_icons.py; do not edit.',
           ' */',
           'html body #wrapwrap :is(.fa, .oi)[class*="-"]::before { box-sizing: content-box; }']
    for key, classes in MAP.items():
        name, _, mode = key.partition('@')
        svg = (Path(icons_dir) / f'{name}.svg').read_text()
        svg = re.sub(r'<!--.*?-->', '', svg, flags=re.S)
        svg = re.sub(r'\s*class="[^"]*"', '', svg)
        svg = svg.replace('stroke-width="2"', 'stroke-width="1.5"').replace('stroke="currentColor"', 'stroke="#000"')
        if mode == 'fill':
            svg = svg.replace('fill="none"', 'fill="#000"')
        svg = re.sub(r'\s+', ' ', svg).strip()
        uri = ('data:image/svg+xml,' + urllib.parse.quote(svg, safe=' =:/"<>.-')).replace('"', "'")
        sel = ',\n'.join(f'html body #wrapwrap .{c}::before' for c in classes)
        css.append(f'{sel} {{\n  content: "" !important; display: inline-block; width: 1em; height: 1em; '
                   f'vertical-align: -0.125em;\n  background-color: currentColor; -webkit-mask: url("{uri}") '
                   f'center / contain no-repeat; mask: url("{uri}") center / contain no-repeat;\n}}')
    OUT.write_text('\n'.join(css) + '\n')
    print(len(MAP), 'icons ->', OUT)


if __name__ == '__main__':
    main(sys.argv[1])
